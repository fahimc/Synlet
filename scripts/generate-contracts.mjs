import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { basename, resolve } from "node:path";
import process from "node:process";

const root = process.cwd();
const schemaDirectory = resolve(root, "packages/contracts/schemas/v1");
const outputPath = resolve(
  root,
  "packages/contracts/src/generated/contracts.ts",
);

function identifier(value) {
  return value
    .replace(/[^a-zA-Z0-9]+(.)/g, (_match, next) => next.toUpperCase())
    .replace(/^[A-Z]/, (letter) => letter.toLowerCase());
}

function typeFromSchema(schema, indentation = "") {
  if (Array.isArray(schema.oneOf)) {
    return schema.oneOf
      .map((item) => typeFromSchema(item, indentation))
      .join(" | ");
  }
  if (Object.hasOwn(schema, "const")) return JSON.stringify(schema.const);
  if (Array.isArray(schema.enum)) {
    return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  }
  if (schema.type === "string") return "string";
  if (schema.type === "integer" || schema.type === "number") return "number";
  if (schema.type === "boolean") return "boolean";
  if (schema.type === "array") {
    return `readonly ${typeFromSchema(schema.items, indentation)}[]`;
  }
  if (schema.type === "object") {
    const required = new Set(schema.required ?? []);
    const entries = Object.entries(schema.properties ?? {}).map(
      ([name, property]) => {
        const optional = required.has(name) ? "" : "?";
        return `${indentation}  readonly ${name}${optional}: ${typeFromSchema(property, `${indentation}  `)};`;
      },
    );
    return [`{`, ...entries, `${indentation}}`].join("\n");
  }
  throw new Error(`Unsupported JSON Schema shape: ${JSON.stringify(schema)}`);
}

async function generate() {
  const filenames = (await readdir(schemaDirectory))
    .filter((name) => name.endsWith(".schema.json"))
    .sort();
  const sections = [];

  for (const filename of filenames) {
    const schema = JSON.parse(
      await readFile(resolve(schemaDirectory, filename), "utf8"),
    );
    if (typeof schema.title !== "string") {
      throw new Error(`${filename} must declare a title`);
    }
    const schemaName = `${identifier(schema.title)}Schema`;
    sections.push(
      `export const ${schemaName} = ${JSON.stringify(schema, null, 2)} as const;`,
      `\nexport type ${schema.title} = ${typeFromSchema(schema)};`,
    );
  }

  return [
    "// Generated by scripts/generate-contracts.mjs. Do not edit by hand.",
    `// Sources: ${filenames.map((name) => basename(name)).join(", ")}`,
    "",
    sections.join("\n\n"),
    "",
  ].join("\n");
}

const expected = await generate();
if (process.argv.includes("--check")) {
  const actual = await readFile(outputPath, "utf8").catch(() => "");
  if (actual !== expected) {
    process.stderr.write(
      "Generated contracts are stale. Run pnpm generate:contracts.\n",
    );
    process.exitCode = 1;
  }
} else {
  await mkdir(resolve(outputPath, ".."), { recursive: true });
  await writeFile(outputPath, expected, "utf8");
  process.stdout.write(`Generated contracts at ${outputPath}\n`);
}
